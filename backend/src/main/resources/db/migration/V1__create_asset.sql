-- Portable between PostgreSQL and H2 (MODE=PostgreSQL).
CREATE TABLE asset (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_tag      VARCHAR(16)   NOT NULL,
    name           VARCHAR(120)  NOT NULL,
    category       VARCHAR(32)   NOT NULL,
    status         VARCHAR(32)   NOT NULL,
    location       VARCHAR(120)  NOT NULL,
    assigned_to    VARCHAR(120),
    purchase_date  DATE,
    purchase_cost  NUMERIC(12, 2),
    notes          VARCHAR(1000),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_asset_tag UNIQUE (asset_tag),
    CONSTRAINT ck_asset_cost CHECK (purchase_cost IS NULL OR purchase_cost >= 0)
);

CREATE INDEX idx_asset_status ON asset (status);
CREATE INDEX idx_asset_category ON asset (category);
